"""CPU-only timing, provenance and PCM acceptance checks for a playlist edition."""
import json
import wave
import argparse
from pathlib import Path

import numpy as np

from scripts.build_storytelling_playlist import ROOT, WORK, MODES, read, sha, write, wave_info
from touchdesigner.storytelling_playlist_sequencer import PodcastSequencer


def validate(root=ROOT, work_dir=WORK):
    root=Path(root)
    work=root/Path(work_dir)
    manifest=read(work/'playlist.json')
    protected=read(work/'protected-inputs.json')
    if any(sha(root/path)!=digest for path,digest in protected.items()):
        raise ValueError('A protected input changed')
    probes=0
    for mode in MODES:
        entry=manifest['plans'][mode]
        if sha(root/entry['path'])!=entry['sha256']:
            raise ValueError('Playlist scene plan changed')
        plan=read(root/entry['path'])
        seq=PodcastSequencer(plan)
        positions=set(range(0,seq.duration_ms,1000))
        for scene in seq.scenes:
            positions.update((scene['start_ms'],max(0,scene['start_ms']-1),scene['end_ms']-1))
            if scene['duration_ms']<15000:
                raise ValueError('Short visual scene')
            for chunk in scene['prompt']['chunks']:
                if not 68<=chunk['content_token_count']<=75:
                    raise ValueError('Invalid SDXL chunk')
        for fade in (0,8000,30000):
            for time in sorted(positions):
                story=seq.story_at(time)
                frame=seq.at(time,crossfade_ms=fade)
                if any(not p.scene_id.startswith(story['narration_id']+'--') for p in frame.prompt_layers):
                    raise ValueError('A story boundary leaks another memory')
                probes+=1
        for story in seq.stories:
            if seq.output_opacity_at(story['start_ms'])!=0:
                raise ValueError('Story boundary fade missing')
    files={kind:root/path for kind,path in manifest['audio'].items()}
    stats={kind:dict(peak=0.,sum_square=0.,samples=0,clipped_samples=0) for kind in files}
    readers={kind:wave.open(str(path),'rb') for kind,path in files.items()}
    residual=0.
    expected_gain=10**(manifest['recipe']['ambient_background_db']/20)
    try:
        while True:
            arrays={k:np.frombuffer(w.readframes(48000*10),dtype='<i2').astype(np.float64)/32768 for k,w in readers.items()}
            if not len(arrays['voices_only']):
                break
            if len({len(a) for a in arrays.values()})!=1:
                raise ValueError('Audio stems have different sample counts')
            for kind,array in arrays.items():
                state=stats[kind]
                state['peak']=max(state['peak'],float(np.abs(array).max()))
                state['sum_square']+=float(np.dot(array,array))
                state['samples']+=len(array)
                state['clipped_samples']+=int(np.sum(np.abs(array)>=32767/32768))
            expected=arrays['voices_only']+arrays['soundscape_only']*expected_gain
            residual=max(residual,float(np.max(np.abs(arrays['combined']-expected))))
    finally:
        for reader in readers.values():
            reader.close()
    for kind,state in stats.items():
        state['rms_dbfs']=float(10*np.log10(state.pop('sum_square')/state['samples']))
        if state['clipped_samples']:
            raise ValueError('Clipped playlist audio')
        if sha(files[kind])!=manifest['audio_sha256'][kind]:
            raise ValueError('Playlist audio hash changed')
        if wave_info(files[kind])['frames']!=manifest['duration_ms']*48:
            raise ValueError('Playlist audio clock changed')
    report=dict(stories=manifest['story_count'],duration_ms=manifest['duration_ms'],
                boundary_probes=probes,protected_inputs=len(protected),audio=stats,
                combined_ambient_gain_db=manifest['recipe']['ambient_background_db'],
                max_mix_residual=residual,network_calls=0,paid_calls=0,passed=True,
                visual_render_review='pending; no images generated by this step')
    write(work/'validation.json',report)
    print(json.dumps(report,indent=2))
    return report


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--work-dir',type=Path,default=WORK)
    args=parser.parse_args()
    validate(work_dir=args.work_dir)
